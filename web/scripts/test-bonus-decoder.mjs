import assert from "node:assert/strict";
import { amount, decode, formatAmount } from "../lib/bonus-decoder.ts";
const input = {bonus:"100",deposit:"50",multiplier:"35",contribution:"100",basis:"bonus"};
assert.equal(decode(input).required,3500);
assert.equal(decode({...input,basis:"deposit-bonus"}).required,5250);
assert.equal(decode({...input,contribution:"50"}).adjusted,7000);
for(const value of ["", " ", "-1", "Infinity", "NaN"]) assert.equal(amount(value),null);
assert.equal(amount("0"),0);
assert.equal(decode({...input,multiplier:"0"}).required,0);
assert.equal(decode({...input,basis:"unknown"}).required,null);
assert.equal(decode({...input,deposit:"",basis:"deposit-bonus"}).required,null);
assert.equal(decode({...input,contribution:"0"}).adjusted,null);
assert.equal(decode({...input,contribution:"101"}).adjusted,null);
assert.equal(decode({...input,bonus:"1e308",multiplier:"1e308"}).required,null);
assert.equal(decode({...input,bonus:"0.00000001",multiplier:"1"}).required,0.00000001);
assert.equal(decode({...input,deposit:"100",basis:"deposit-bonus",contribution:"25"}).adjusted,28000);
assert.equal(formatAmount(null,"USD"),"Unknown");
assert.equal(formatAmount(0,"BTC"),"0 BTC");
assert.equal(formatAmount(1e-18,"ETH"),"1.000000e-18 ETH");
assert.equal(formatAmount(3500,"EUR"),"3,500 EUR");
console.log("Decoder: 21 assertions passed");
